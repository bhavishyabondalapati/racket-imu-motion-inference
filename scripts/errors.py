"""D7: error analysis of the D3 random forest. Writes docs/ERRORS.md and docs/figures/d7/.

Usage:
    python scripts/errors.py [--config configs/default.yaml] [--d3-run results/d3_...]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from racketimu import errors as E
from racketimu.config import PROJECT_ROOT, load_config
from racketimu.datacard import md_table
from racketimu.plots import plot_failure_cases
from racketimu.runinfo import git_state

MODEL = "rf_primary"
SHOW = ["sample_id", "test_player", "level", "true", "pred", "confidence", "n_rows", "peak_row"]


def latest_run(cfg: dict, prefix: str) -> Path:
    runs = sorted((PROJECT_ROOT / cfg["paths"]["results"]).glob(f"{prefix}_*"))
    if not runs:
        raise FileNotFoundError(f"No {prefix} results found. Run the earlier milestone first.")
    return runs[-1]


def pattern_lines(df, players, low, conf) -> list[str]:
    gap = E.level_gap(players)
    pairs = E.confusion_pairs(df)
    top = pairs.iloc[0]
    bt = pairs[pairs["true"].isin(["BASIC", "TOPSPIN"]) & pairs["pred"].isin(["BASIC", "TOPSPIN"])]
    first_row = df["peak_row"] == 0
    conf_pairs = conf.groupby(["true", "pred"]).size().sort_values(ascending=False)
    bins = pd.cut(df["n_rows"], [0, 15, 25, 40, 10_000], labels=["2-15", "16-25", "26-40", "41+"])
    g = df.assign(b=bins).groupby("b", observed=True)["correct"]
    lengths = pd.DataFrame({"rate": 1 - g.mean(), "n": g.size()})
    cl = df.groupby(["true", "level"])["correct"].agg(["mean", "size"]).reset_index()
    worst = cl.assign(rate=1 - cl["mean"], n=cl["size"]).sort_values("rate").iloc[-1]
    push_rate = 1 - df.loc[df["true"] == "PUSH", "correct"].mean()
    return [
        f"- **Where the errors are:** {int((~df['correct']).sum())} of {len(df)} strokes are "
        f"misclassified. The largest error type is {top['true']} predicted as {top['pred']} "
        f"({top['errors']}); basic/topspin confusions in either direction account for "
        f"{bt['errors'].sum()} of {pairs['errors'].sum()} errors.",
        "- **Confident errors:** of the 10 most confident mistakes, "
        + ", ".join(
            f"{n} {'is' if n == 1 else 'are'} {t} predicted as {p}"
            for (t, p), n in conf_pairs.items()
        )
        + f"; they come from {conf['test_player'].nunique()} players "
        f"({', '.join(conf['test_player'].value_counts().index)}). Their confidence ranges from "
        f"{conf['confidence'].min():.2f} to {conf['confidence'].max():.2f}.",
        f"- **Unconfident strokes:** the 10 lowest-confidence strokes have confidence "
        f"{low['confidence'].min():.2f}-{low['confidence'].max():.2f}; "
        f"{int(low['correct'].sum())} of them are still correct.",
        f"- **Per-player spread:** accuracy ranges from {players['accuracy'].min():.3f} "
        f"({players.index[0]}) to {players['accuracy'].max():.3f}. Mean per-player accuracy is "
        f"{gap.get('novice', np.nan):.3f} for novices and {gap.get('pro', np.nan):.3f} for pros "
        "(players weighted equally).",
        "- **Stroke length:** error rate by number of rows in the stroke file: "
        + ", ".join(f"{r.Index} rows {r.rate:.3f} (n={r.n})" for r in lengths.itertuples())
        + ".",
        f"- **Class and level:** the highest error rate is {worst.true} by {worst.level}s "
        f"({worst.rate:.3f}, n={worst.n}); push is almost never misclassified "
        f"({push_rate:.3f} overall).",
        f"- **Peak on the first row:** error rate {1 - df.loc[first_row, 'correct'].mean():.3f} "
        f"for the {int(first_row.sum())} strokes whose peak is on the first logged row, vs "
        f"{1 - df.loc[~first_row, 'correct'].mean():.3f} for the rest.",
    ]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", default=None)
    parser.add_argument("--d3-run", default=None)
    args = parser.parse_args()
    cfg = load_config(args.config)
    try:
        run = (PROJECT_ROOT / args.d3_run).resolve() if args.d3_run else latest_run(cfg, "d3")
    except FileNotFoundError as err:
        print(f"ERROR: {err}", file=sys.stderr)
        return 1
    windows = pd.read_parquet(PROJECT_ROOT / cfg["paths"]["processed"] / "strokes.parquet")
    oof = pd.read_csv(run / "oof_predictions.csv.gz")
    df = E.attach_window_info(E.seed_averaged(oof, MODEL), windows)
    players, low, conf = E.per_player(df), E.lowest_confidence(df), E.confident_errors(df)
    figs = PROJECT_ROOT / cfg["paths"]["figures"] / "d7"
    cases = conf.head(4)
    plot_failure_cases(windows, df, cases, figs / "failure_cases.png")
    rows_bin = pd.cut(
        df["n_rows"], [0, 15, 25, 40, 10_000], labels=["2-15", "16-25", "26-40", "41+"]
    )
    git = git_state()
    lines = [
        "# Error analysis (D7)",
        "",
        "> Generated by `make errors` (`scripts/errors.py`) from "
        f"`{run.relative_to(PROJECT_ROOT)}` "
        f"(model: random forest on handcrafted primary features; probabilities averaged over "
        f"the 3 seeds, uncalibrated). Code commit `{git['commit'][:10]}`. Do not edit by hand.",
        "",
        "## Patterns found",
        "",
        *pattern_lines(df, players, low, conf),
        "",
        "These describe the out-of-fold predictions only. The leak check in D3 suggests the model "
        "relies mostly on static racket orientation, which is the lens for the failure plots "
        "below.",
        "",
        "## Error types",
        "",
        md_table(E.confusion_pairs(df), index=False),
        "",
        "## 10 misclassified strokes with the highest confidence",
        "",
        md_table(conf[SHOW].round(3), index=False),
        "",
        "## 10 lowest-confidence strokes",
        "",
        md_table(low[[*SHOW, "correct"]].round(3), index=False),
        "",
        "## Per test player (accuracy, lowest first)",
        "",
        md_table(players),
        "",
        "## Error rate by stroke length (raw rows)",
        "",
        md_table(E.error_rates(df, rows_bin, "rows in stroke file")),
        "",
        "## Error rate by true class and level",
        "",
        md_table(
            df.groupby(["true", "level"]).agg(
                n=("correct", "size"), error_rate=("correct", lambda s: round(1 - s.mean(), 3))
            )
        ),
        "",
        "## Failure cases",
        "",
        "`figures/d7/failure_cases.png`: the 4 most confident errors (dark line) against the "
        "median and interquartile band of their true class and of the predicted class, for roll, "
        "pitch and gyro magnitude.",
        "",
        "![failure cases](figures/d7/failure_cases.png)",
    ]
    (PROJECT_ROOT / cfg["paths"]["docs"] / "ERRORS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:14]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
